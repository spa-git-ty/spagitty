    /// The directory is replaced wholesale by `omarchy-theme-set`, so the
    /// answer has to come from the path each time rather than from anything
    /// cached against an inode.
    #[test]
    #[cfg(target_os = "linux")]
    fn follows_the_directory_being_replaced() {
        let dir = TempDir::new().unwrap();
        install(dir.path(), "first", REAL);
        let env = env_for(dir.path());
        assert_eq!(detect(&env).palette.unwrap().background, "#191724");

        // What the script does: build the next one beside it, then swap.
        let current = dir.path().join(".local/state/omarchy/current");
        let next = current.join("next-theme");
        fs::create_dir_all(&next).unwrap();
        fs::write(
            next.join("colors.toml"),
            "mode = \"light\"\nbackground = \"#faf4ed\"\nforeground = \"#575279\"\n",
        )
        .unwrap();
        fs::remove_dir_all(current.join("theme")).unwrap();
        fs::rename(&next, current.join("theme")).unwrap();
        fs::write(current.join("theme.name"), "rose-pine-dawn\n").unwrap();

        let found = detect(&env);
        assert_eq!(found.name.as_deref(), Some("rose-pine-dawn"));
        assert_eq!(found.palette.unwrap().background, "#faf4ed");
    }

