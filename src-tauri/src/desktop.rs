//! The desktop's own colours, where the desktop publishes them (FEAT-080).
//!
//! Omarchy keeps the active theme as files on disk, and every other application
//! on the machine — the terminal, the editor, the bar — already follows them.
//! Spagitty was the window that did not match. This module is the whole of the
//! reading side: find the palette, parse it, validate it, hand back a typed
//! answer, and say when it changes.
//!
//! # What this module deliberately does not do
//!
//! **It does not decide what anything looks like.** It returns the desktop's
//! own semantic roles — background, foreground, accent, the status hues — and
//! nothing else. Turning those into Spagitty's fourteen tokens is a design
//! decision with contrast arithmetic in it, and it lives beside the other
//! palettes in `src/lib/omarchy.ts` where `themes.test.ts` can hold it to the
//! same ratios as the built-in families. Splitting it the other way would put
//! colour design in Rust and leave the frontend unable to check it.
//!
//! **It does not expose a path.** The frontend cannot ask this module to read
//! an arbitrary file; it can ask "what is the desktop's palette", and gets a
//! validated struct or nothing. A general "read this file" command reachable
//! from the webview would be a much larger thing to have built than a theme.
//!
//! **It does not source or execute anything.** Omarchy's theme directory also
//! holds `hyprland.lua`, `gum_env.lua`, `neovim.lua` and a `vscode-theme.json`.
//! Only `colors.toml` is read, and only as data.
//!
//! # Finding it
//!
//! Two layouts, because Omarchy moved and installations lag:
//!
//! | Layout  | Palette | Name |
//! |---------|---------|------|
//! | state   | `$XDG_STATE_HOME/omarchy/current/theme/colors.toml` | `current/theme.name` |
//! | legacy  | `$XDG_CONFIG_HOME/omarchy/current/theme/colors.toml` | the `current/theme` symlink's target |
//!
//! `$XDG_STATE_HOME` defaults to `~/.local/state` and `$XDG_CONFIG_HOME` to
//! `~/.config`, which is what Omarchy's own scripts use. The machine this was
//! written on has the state layout and no `~/.config/omarchy` at all.
//!
//! Detection is **evidence, not inference**. `XDG_CURRENT_DESKTOP=Hyprland` is
//! not proof of Omarchy — plenty of Hyprland installations are not Omarchy, and
//! Omarchy under a different session would be missed. What counts is an
//! Omarchy-shaped state or config directory *and* a palette in it that parses.
//! A directory with no usable palette is reported as not available rather than
//! as a broken Omarchy, because from Spagitty's side those are the same thing.
//!
//! # Why the parser is written here rather than pulled in
//!
//! `colors.toml` is generated by `omarchy-themes` and is a flat list of
//! `key = "value"` pairs with comments. It has no tables, no arrays, no
//! datetimes, no multi-line strings and no nesting. A TOML crate would parse a
//! language where this file is a sentence, and it would be a new direct
//! dependency in the binary to do it — which Amendment's forbidden-changes rule
//! asks to be justified rather than assumed.
//!
//! So the scanner below reads exactly that sentence: top-level quoted scalars,
//! a bounded number of them, from a bounded number of bytes, stopping dead at
//! the first `[table]` header so that a future file which *does* grow sections
//! is under-read rather than mis-read. It is about forty lines and every one of
//! its refusals is a test.
//!
//! # Watching
//!
//! `omarchy-theme-set` does not edit `colors.toml`. It builds a `next-theme`
//! directory and **replaces** `current/theme`, so a watch on the palette file's
//! own inode sees the first change and nothing after it. The watch is therefore
//! on the stable parent — `current`, and the directory above it — and the
//! palette is re-read from the path each time.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::mpsc::{channel, Receiver, RecvTimeoutError, Sender};
use std::sync::Mutex;
use std::thread::JoinHandle;
use std::time::Duration;

use notify::{RecursiveMode, Watcher};
use serde::Serialize;
use tauri::{AppHandle, Emitter, Manager, Runtime, State};

/// Emitted when the desktop's palette has changed under us.
pub const THEME_CHANGED_EVENT: &str = "desktop-theme-changed";

/// The most of `colors.toml` that will ever be read.
///
/// The real file is about 1.3 KiB. This is not a performance limit — it is the
/// answer to "what if this path is a 4 GiB file or a fifo", which is a question
/// worth having an answer to for any path the application did not write.
const MAX_PALETTE_BYTES: u64 = 64 * 1024;

/// The most keys that will be kept from one file.
const MAX_KEYS: usize = 256;

/// The longest value that can be a colour. `color-mix(...)` is nowhere near it.
const MAX_VALUE_LEN: usize = 200;

/// A theme change is several filesystem events; coalesce them, as `watch` does.
const QUIET_PERIOD: Duration = Duration::from_millis(200);

/// Which layout the palette was found in. Reported so a bug report can say.
#[derive(Serialize, Clone, Copy, PartialEq, Eq, Debug)]
#[serde(rename_all = "camelCase")]
pub enum Layout {
    /// `$XDG_STATE_HOME/omarchy` — what current Omarchy uses.
    State,
    /// `$XDG_CONFIG_HOME/omarchy` — the older location.
    Legacy,
}

/// The desktop's palette, in the desktop's own vocabulary.
///
/// Every field is optional except the two that make a palette a palette,
/// because a theme generator is free to omit any of them and a half-read file
/// must not become a half-painted application. What the frontend does with the
/// gaps — derive, fall back to an ANSI slot, or refuse — is its decision, and
/// the shape of this struct is what lets it make one.
#[derive(Serialize, Clone, PartialEq, Eq, Debug, Default)]
#[serde(rename_all = "camelCase")]
pub struct DesktopPalette {
    /// `dark` or `light`, from the file's own `mode` where it has one.
    pub mode: Option<String>,
    pub background: String,
    pub foreground: String,
    pub accent: Option<String>,
    /// A step down from the background — window chrome.
    pub dark_bg: Option<String>,
    /// A step up from it — a raised surface.
    pub lighter_bg: Option<String>,
    /// The desktop's own idea of secondary text. **Often unreadable**: on the
    /// palette this was written against it is 2.75:1 on the background, so the
    /// frontend derives its own and keeps this for hue only.
    pub muted: Option<String>,
    pub selection_background: Option<String>,
    pub selection_foreground: Option<String>,
    /// Semantic hues, where the generator names them.
    pub red: Option<String>,
    pub green: Option<String>,
    pub yellow: Option<String>,
    pub blue: Option<String>,
    pub magenta: Option<String>,
    pub cyan: Option<String>,
    /// ANSI slots 0-15, as compatibility fallbacks for the hues above.
    pub ansi: Vec<Option<String>>,
}

/// What the frontend gets back, whether or not there is anything to follow.
#[derive(Serialize, Clone, PartialEq, Eq, Debug, Default)]
#[serde(rename_all = "camelCase")]
pub struct DesktopTheme {
    /// True only with a usable palette. The option in Settings keys off this.
    pub available: bool,
    /// The desktop's name for what is on — `sushi-dark-palette`.
    pub name: Option<String>,
    pub layout: Option<Layout>,
    pub palette: Option<DesktopPalette>,
    /// Why not, when `available` is false. For the Appearance screen's quiet
    /// status line, and for a bug report. Never a path the user did not give.
    pub reason: Option<String>,
}

impl DesktopTheme {
    fn unavailable(reason: &str) -> Self {
        Self {
            reason: Some(reason.to_string()),
            ..Default::default()
        }
    }
}

// --- Parsing --------------------------------------------------------------

/// Whether `value` is shaped like a colour this application may write into CSS.
///
/// The palette file is not hostile, but it is not ours either: it is generated
/// by another program, on a schedule nobody here controls, and its contents end
/// up as custom property values on the root element. So the check is a
/// whitelist of shapes rather than a blacklist of characters — a hex triple or
/// quad, in either case, with or without the `#`.
///
/// Deliberately narrower than CSS allows. Omarchy writes `#rrggbb` and nothing
/// else; accepting `rgb()` and named colours as well would widen the surface
/// for no file that exists.
fn is_colour(value: &str) -> bool {
    let hex = value.strip_prefix('#').unwrap_or(value);
    matches!(hex.len(), 3 | 4 | 6 | 8) && hex.chars().all(|c| c.is_ascii_hexdigit())
}

/// Normalise a colour to `#rrggbb`-style, so the frontend never sees two
/// spellings of the same value.
fn colour(value: &str) -> Option<String> {
    if !is_colour(value) {
        return None;
    }
    let hex = value.strip_prefix('#').unwrap_or(value);
    Some(format!("#{}", hex.to_ascii_lowercase()))
}

/// Read the flat top-level scalars out of a generated TOML file.
///
/// Everything this does *not* do is the point:
///
/// - it stops at the first `[section]` header, so a file that grows tables
///   later is read as far as it is understood and no further;
/// - it ignores anything that is not `key = "value"` or `key = 'value'`,
///   including bare numbers and booleans, which no colour is;
/// - it takes at most [`MAX_KEYS`] pairs and drops values over
///   [`MAX_VALUE_LEN`];
/// - it never unescapes, because a colour has no escapes and a parser that
///   handles `\u` is a parser with a bug in it waiting.
fn scan(text: &str) -> HashMap<String, String> {
    let mut out = HashMap::new();

    for line in text.lines() {
        if out.len() >= MAX_KEYS {
            break;
        }

        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // A table header. Everything after it is nested, and nothing here
        // knows how to say so.
        if line.starts_with('[') {
            break;
        }

        let Some((key, rest)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        if key.is_empty() || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            continue;
        }

        // The value, up to a trailing comment. Comments are only stripped
        // *outside* the quotes, which is why the quoted span is taken first.
        let rest = rest.trim();
        let quote = match rest.chars().next() {
            Some(c @ ('"' | '\'')) => c,
            // Unquoted: a number, a boolean, a date. Not a colour.
            _ => continue,
        };
        let Some(end) = rest[1..].find(quote) else {
            continue;
        };
        let value = &rest[1..1 + end];

        if value.len() > MAX_VALUE_LEN {
            continue;
        }
        out.insert(key.to_string(), value.to_string());
    }

    out
}

/// Build the typed palette from the scanned pairs, or nothing.
///
/// Two fields are required — a background and a foreground — because a palette
/// missing either is not a palette anybody could paint with, and reporting it
/// as available would mean Spagitty following a desktop into an unreadable
/// window. Everything else is optional and derived on the other side.
fn palette_from(pairs: &HashMap<String, String>) -> Option<DesktopPalette> {
    let pick = |names: &[&str]| -> Option<String> {
        names
            .iter()
            .find_map(|name| pairs.get(*name).and_then(|value| colour(value)))
    };

    let background = pick(&["background", "bg"])?;
    let foreground = pick(&["foreground", "fg"])?;

    // 0-15, each present or not. A gap is kept as a gap rather than closed up,
    // because slot 4 means blue and slot 5 means magenta — an ANSI palette is
    // positional and compacting it would silently recolour the graph.
    let ansi = (0..16)
        .map(|index| pairs.get(&format!("color{index}")).and_then(|v| colour(v)))
        .collect();

    let mode = pairs
        .get("mode")
        .and_then(|value| matches!(value.as_str(), "dark" | "light").then(|| value.to_string()));

    Some(DesktopPalette {
        mode,
        background,
        foreground,
        accent: pick(&["accent", "selection"]),
        dark_bg: pick(&["dark_bg", "darker_bg"]),
        lighter_bg: pick(&["lighter_bg"]),
        muted: pick(&["muted"]),
        selection_background: pick(&["selection_background"]),
        selection_foreground: pick(&["selection_foreground"]),
        red: pick(&["red"]),
        green: pick(&["green"]),
        yellow: pick(&["yellow"]),
        blue: pick(&["blue"]),
        magenta: pick(&["magenta"]),
        cyan: pick(&["cyan"]),
        ansi,
    })
}

// --- Finding it -----------------------------------------------------------

/// `$XDG_STATE_HOME`, or the default every Omarchy script uses.
fn state_home(env: &dyn Fn(&str) -> Option<String>) -> Option<PathBuf> {
    if let Some(explicit) = env("XDG_STATE_HOME").filter(|value| !value.is_empty()) {
        return Some(PathBuf::from(explicit));
    }
    Some(PathBuf::from(env("HOME")?).join(".local/state"))
}

/// `$XDG_CONFIG_HOME`, or its default.
fn config_home(env: &dyn Fn(&str) -> Option<String>) -> Option<PathBuf> {
    if let Some(explicit) = env("XDG_CONFIG_HOME").filter(|value| !value.is_empty()) {
        return Some(PathBuf::from(explicit));
    }
    Some(PathBuf::from(env("HOME")?).join(".config"))
}

/// The two roots to try, newest layout first.
///
/// Pure and taking its environment as a function, so the table of cases is a
/// test rather than a claim about the machine this was written on.
pub fn roots(env: &dyn Fn(&str) -> Option<String>) -> Vec<(Layout, PathBuf)> {
    let mut out = Vec::new();
    if let Some(path) = state_home(env) {
        out.push((Layout::State, path.join("omarchy")));
    }
    if let Some(path) = config_home(env) {
        out.push((Layout::Legacy, path.join("omarchy")));
    }
    out
}

/// Where the palette lives under a root, and where the name does.
fn palette_path(root: &Path) -> PathBuf {
    root.join("current/theme/colors.toml")
}

/// The theme's own name.
///
/// `theme.name` is what current Omarchy writes. The older layout has no such
/// file and instead makes `current/theme` a symlink into the themes directory,
/// so the link's target names the theme. Both are tried; neither is required,
/// because a nameless palette is still a palette.
fn theme_name(root: &Path) -> Option<String> {
    let named = root.join("current/theme.name");
    if let Ok(text) = std::fs::read_to_string(&named) {
        let name = text.trim();
        // A name is a label in a settings screen, not a path. Anything with a
        // separator in it is not one.
        if !name.is_empty() && name.len() <= 64 && !name.contains(['/', '\\', '\n']) {
            return Some(name.to_string());
        }
    }

    std::fs::read_link(root.join("current/theme"))
        .ok()?
        .file_name()?
        .to_str()
        .map(|name| name.to_string())
}

/// Read a file, refusing anything that is not a bounded regular file.
fn read_bounded(path: &Path) -> Option<String> {
    let meta = std::fs::metadata(path).ok()?;
    if !meta.is_file() || meta.len() > MAX_PALETTE_BYTES {
        return None;
    }
    std::fs::read_to_string(path).ok()
}

/// What the desktop is currently painted with, if anything.
///
/// Takes its environment so the whole search is testable against a temporary
/// directory rather than against whoever's machine runs the suite.
pub fn detect(env: &dyn Fn(&str) -> Option<String>) -> DesktopTheme {
    if !cfg!(target_os = "linux") {
        return DesktopTheme::unavailable("Omarchy is a Linux desktop");
    }

    let candidates = roots(env);
    if candidates.is_empty() {
        return DesktopTheme::unavailable("no home directory to look in");
    }

    let mut found_root = false;
    for (layout, root) in candidates {
        if !root.is_dir() {
            continue;
        }
        found_root = true;

        let Some(text) = read_bounded(&palette_path(&root)) else {
            continue;
        };
        let Some(palette) = palette_from(&scan(&text)) else {
            continue;
        };

        return DesktopTheme {
            available: true,
            name: theme_name(&root),
            layout: Some(layout),
            palette: Some(palette),
            reason: None,
        };
    }

    // The two cases are worth telling apart in a status line: one is "you are
    // not running Omarchy", the other is "you are, and its palette is not
    // readable", and only the second is worth reporting to anybody.
    DesktopTheme::unavailable(if found_root {
        "Omarchy is installed but its active palette could not be read"
    } else {
        "Omarchy was not detected"
    })
}

// --- Watching -------------------------------------------------------------

/// Holds the watcher alive. Dropping it stops watching and joins the thread.
pub struct ThemeWatcher {
    _watcher: notify::RecommendedWatcher,
    stop: Sender<()>,
    handle: Option<JoinHandle<()>>,
}

impl Drop for ThemeWatcher {
    fn drop(&mut self) {
        let _ = self.stop.send(());
        if let Some(handle) = self.handle.take() {
            let _ = handle.join();
        }
    }
}

/// The watcher, when one is running. Managed state, so the command layer can
/// start and stop it without the frontend holding a handle.
#[derive(Default)]
pub struct DesktopState {
    watcher: Mutex<Option<ThemeWatcher>>,
}

fn environment(name: &str) -> Option<String> {
    std::env::var(name).ok()
}

/// Start watching for a theme change, replacing any watch already running.
///
/// **The watch is on the directory, not the file.** `omarchy-theme-set` builds
/// a `next-theme` directory and replaces `current/theme` wholesale, so a
/// watcher registered against `colors.toml` follows an inode that stops being
/// the current palette after the first change — it would work once, in testing,
/// and then never again.
///
/// Two registrations, then: `current` recursively, which is small and is where
/// the replacement happens, and the root itself non-recursively, in case
/// `current` is what gets replaced.
fn start<R: Runtime>(app: AppHandle<R>) -> Option<ThemeWatcher> {
    let (layout_root, _) = roots(&environment)
        .into_iter()
        .find(|(_, root)| root.is_dir())
        .map(|(layout, root)| (root, layout))?;

    let (event_tx, event_rx) = channel::<notify::Result<notify::Event>>();
    let (stop_tx, stop_rx) = channel::<()>();

    let mut watcher = notify::recommended_watcher(move |res| {
        let _ = event_tx.send(res);
    })
    .ok()?;

    // Either registration may fail — `current` might not exist yet on a fresh
    // install — and one is enough to notice a change, so neither is fatal.
    let current = layout_root.join("current");
    let watched = watcher.watch(&current, RecursiveMode::Recursive).is_ok()
        | watcher
            .watch(&layout_root, RecursiveMode::NonRecursive)
            .is_ok();
    if !watched {
        return None;
    }

    let handle = std::thread::Builder::new()
        .name("spagitty-desktop-theme".into())
        .spawn(move || debounce(app, event_rx, stop_rx))
        .ok()?;

    Some(ThemeWatcher {
        _watcher: watcher,
        stop: stop_tx,
        handle: Some(handle),
    })
}

/// Coalesce a burst of events into one re-read, and emit only real changes.
///
/// The last valid palette is kept and compared against, for two reasons. A
/// theme switch touches a directory of twenty files and would otherwise emit
/// twenty times; and a *partial* update — the moment after the old directory
/// has gone and before the new one is in place — reads as unavailable, which
/// would blank the application's colours for a frame in the middle of a theme
/// change. An unreadable read is therefore dropped rather than reported, and
/// the palette that was last valid stays on screen until a new valid one
/// arrives.
fn debounce<R: Runtime>(
    app: AppHandle<R>,
    events: Receiver<notify::Result<notify::Event>>,
    stop: Receiver<()>,
) {
    let mut last = detect(&environment);

    loop {
        if stop.try_recv().is_ok() {
            return;
        }

        match events.recv_timeout(Duration::from_millis(250)) {
            Ok(_) => {}
            Err(RecvTimeoutError::Timeout) => continue,
            Err(RecvTimeoutError::Disconnected) => return,
        }

        // Keep draining until it goes quiet. A disconnected channel means the
        // watcher has been dropped, and there is nothing left to report to.
        if drain(&events) == RecvTimeoutError::Disconnected {
            return;
        }

        let next = detect(&environment);

        // Mid-replacement. Hold what we have; another event is coming.
        if !next.available && last.available {
            continue;
        }
        if next == last {
            continue;
        }

        last = next.clone();
        let _ = app.emit(THEME_CHANGED_EVENT, next);
    }
}

/// Wait out the quiet period, swallowing whatever arrives during it.
///
/// Returns why it stopped: `Timeout` is the theme change having finished, and
/// `Disconnected` is the watcher having been dropped out from under us.
fn drain(events: &Receiver<notify::Result<notify::Event>>) -> RecvTimeoutError {
    loop {
        match events.recv_timeout(QUIET_PERIOD) {
            Ok(_) => continue,
            Err(error) => return error,
        }
    }
}

// --- Commands -------------------------------------------------------------

/// Register the desktop state. Called once, from `run`.
pub fn manage<R: Runtime>(app: &AppHandle<R>) {
    app.manage(DesktopState::default());
}

/// What the desktop is painted with right now.
#[tauri::command]
pub fn desktop_theme() -> DesktopTheme {
    detect(&environment)
}

/// Start telling the frontend when it changes.
///
/// Idempotent: called again, it replaces the watch rather than adding one.
/// Returns whether a watch is running, which is not the same question as
/// whether a palette was found — a machine can have Omarchy and an inotify
/// limit already exhausted, and the answer there is "the theme works, live
/// updates do not", which the Appearance screen can say.
#[tauri::command]
pub fn desktop_theme_watch<R: Runtime>(app: AppHandle<R>, state: State<'_, DesktopState>) -> bool {
    let mut slot = state.watcher.lock().expect("desktop watcher");
    // Dropped first, so the old thread is joined before a new one starts and
    // two watchers never emit into the same window.
    *slot = None;
    *slot = start(app);
    slot.is_some()
}

/// Stop watching. Called when the user picks a theme source that is not the
/// desktop, and when the window goes away.
#[tauri::command]
pub fn desktop_theme_unwatch(state: State<'_, DesktopState>) {
    *state.watcher.lock().expect("desktop watcher") = None;
}

