/**
 * The attribution check gate 1 runs on a pull request (TASK-064): an agent,
 * a tool or a session named as an author is refused, a person is not, and
 * prose that merely mentions an agent is left alone.
 */

import { describe, expect, it } from 'vitest';
import { findAttribution } from './attribution.mjs';

describe('findAttribution', () => {
	it('refuses a co-author that is an agent or a tool', () => {
		const message = [
			'fix(x): a change',
			'',
			'Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>',
			'co-authored-by: Codex <codex@openai.com>',
			'Co-authored-by: GitHub Copilot <copilot@github.com>'
		].join('\n');
		expect(findAttribution(message)).toHaveLength(3);
	});

	it('refuses a session trailer and a generated-with line', () => {
		expect(findAttribution('Claude-Session: abc123')).toEqual(['Claude-Session: abc123']);
		expect(findAttribution('🤖 Generated with [Claude Code](https://claude.com/claude-code)')).toHaveLength(1);
		expect(findAttribution('_Generated by [Claude Code](https://claude.ai/code)_')).toHaveLength(1);
	});

	it('lets a person be a co-author', () => {
		expect(findAttribution('Co-authored-by: Ada Lovelace <ada@example.com>')).toEqual([]);
	});

	it('leaves prose that names an agent alone', () => {
		const prose = [
			'fix(models): send Gemini what it accepts',
			'',
			'Claude Code runs read-only. Codex has a Full access option.',
			'Settings › Agents lists Claude Code, Codex and agy.'
		].join('\n');
		expect(findAttribution(prose)).toEqual([]);
	});

	it('reads a message with Windows line endings', () => {
		expect(findAttribution('subject\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n')).toHaveLength(1);
	});
});
